export function toCyrillic(text: string): string {
  let result = text;
  for (const [pattern, repl] of LATIN_TO_CYRILLIC_MAP) {
    result = result.replace(pattern, repl);
  }
  return result;
}

export function toLatin(text: string): string {
  let result = text;
  for (const [pattern, repl] of CYRILLIC_TO_LATIN_MAP) {
    result = result.replace(pattern, repl);
  }
  return result;
}
